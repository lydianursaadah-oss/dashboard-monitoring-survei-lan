import {
  bigint,
  bigserial,
  date,
  integer,
  jsonb,
  pgTable,
  text,
  timestamp,
} from 'drizzle-orm/pg-core'

export const publikasi = pgTable('publikasi', {
  id: bigserial('id', { mode: 'number' }).primaryKey(),
  no: integer('no'),
  unit: text('unit').notNull(),
  judul: text('judul').notNull(),
  jenis: text('jenis').default(''),
  jadwal: text('jadwal').default(''),
  tahun: text('tahun').default('2026'),
  cluster: text('cluster').default(''),
  jurnal: text('jurnal').default(''),
  media: text('media').default(''),
  webLan: text('web_lan').default(''),
  webUnit: text('web_unit').default(''),
  igLan: text('ig_lan').default(''),
  igUnit: text('ig_unit').default(''),
  ytLan: text('yt_lan').default(''),
  ytUnit: text('yt_unit').default(''),
  ket: text('ket').default(''),
  createdAt: timestamp('created_at', { withTimezone: true }).defaultNow(),
})

export const users = pgTable('users', {
  id: bigint('id', { mode: 'number' }).primaryKey().generatedByDefaultAsIdentity(),
  username: text('username').notNull().unique(),
  password: text('password').notNull(),
  nama: text('nama').notNull(),
  jabatan: text('jabatan').notNull(),
  unit: text('unit').notNull(),
  role: text('role').notNull(),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
})

export const prismoProposals = pgTable('prismo_proposals', {
  id: text('id').primaryKey(),
  judul: text('judul').notNull(),
  unit: text('unit').notNull(),
  jenis: text('jenis').default('Survei'),
  cluster: text('cluster'),
  latarBelakang: text('latar_belakang'),
  tujuan: text('tujuan'),
  pic: text('pic'),
  targetSelesai: date('target_selesai'),
  jadwal: text('jadwal'),
  tahun: integer('tahun').default(2026),
  dokumenProposal: text('dokumen_proposal'),
  dokumenJadwal: text('dokumen_jadwal'),
  status: text('status').default('diajukan'),
  prioritas: text('prioritas').default('Normal'),
  diajukanTgl: date('diajukan_tgl').defaultNow(),
  diverifikasiTgl: date('diverifikasi_tgl'),
  disetujuiTgl: date('disetujui_tgl'),
  checklistAdmin: jsonb('checklist_admin').$type<Record<string, boolean>>().default({}),
  catatanAdmin: text('catatan_admin').default(''),
  keputusanKepala: text('keputusan_kepala'),
  catatanKepala: text('catatan_kepala').default(''),
  catatanRevisi: text('catatan_revisi').default(''),
  riwayat: jsonb('riwayat').$type<Array<Record<string, unknown>>>().default([]),
  createdAt: timestamp('created_at', { withTimezone: true }).defaultNow(),
  updatedAt: timestamp('updated_at', { withTimezone: true }).defaultNow(),
})
